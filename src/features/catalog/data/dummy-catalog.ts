export function getDummyAssets(kind: AssetKind): AssetDetailDto[] {
  return kind === 'Model' ? DUMMY_MODELS : DUMMY_DATASETS;
}

export function buildAssetFacets(items: readonly AssetDetailDto[]): AssetFacets {
  const dtypeMap = new Map<string, number>();
  const licMap = new Map<string, { slug: string; name: string; count: number }>();

  for (const item of items) {
    dtypeMap.set(item.dataType, (dtypeMap.get(item.dataType) ?? 0) + 1);
    if (item.license) {
      const prev = licMap.get(item.license.slug);
      if (prev) {
        prev.count += 1;
      } else {
        licMap.set(item.license.slug, {
          slug: item.license.slug,
          name: item.license.name ?? item.license.slug,
          count: 1,
        });
      }
    }
  }

  return {
    dataTypes: Array.from(dtypeMap.entries()).map(([value, count]) => ({ value, count })),
    licenses: Array.from(licMap.values()),
  };
}
