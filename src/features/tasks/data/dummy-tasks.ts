export function buildTaskFacets(tasks: readonly TaskDetail[]): TaskFacets {
  const dtypeMap = new Map<string, number>();
  const catMap = new Map<string, { slug: string; name: string; count: number }>();
  const diffMap = new Map<string, number>();

  for (const t of tasks) {
    dtypeMap.set(t.dataType, (dtypeMap.get(t.dataType) ?? 0) + 1);
    if (t.categorySlug) {
      const prev = catMap.get(t.categorySlug);
      if (prev) prev.count += 1;
      else catMap.set(t.categorySlug, { slug: t.categorySlug, name: t.category, count: 1 });
    }
    diffMap.set(t.difficulty, (diffMap.get(t.difficulty) ?? 0) + 1);
  }

  return {
    dataTypes: Array.from(dtypeMap.entries()).map(([value, count]) => ({ value, count })),
    categories: Array.from(catMap.values()),
    difficulties: Array.from(diffMap.entries()).map(([value, count]) => ({ value, count })),
    total: tasks.length,
  };
}

export function workspaceTypeForTask(type: TaskTypeId): TaskDetail | undefined {
  return DUMMY_TASKS.find((t) => t.type === type);
}
